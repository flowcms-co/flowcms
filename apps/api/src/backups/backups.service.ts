import { BadRequestException, Injectable, Logger, NotFoundException, OnModuleDestroy, OnModuleInit, Optional } from "@nestjs/common";
import { createHash } from "node:crypto";
import { brotliCompressSync, brotliDecompressSync, constants as z } from "node:zlib";
import { Prisma } from "@flowcms/db";
import { PrismaService } from "../prisma/prisma.service";
import { RedisService } from "../redis/redis.service";
import { WebhooksService } from "../webhooks/webhooks.service";
import { CacheService } from "../cache/cache.service";
import { AuditService } from "../audit/audit.service";
import { currentActor } from "../common/request-context";

type Row = Record<string, unknown> & { id: string };
/** What a snapshot holds. Version history isn't copied (it would dwarf the
 *  content); a rollback keeps the versions already there. */
type Snapshot = {
    format: 1;
    takenAt: string;
    types: Row[];
    entries: Row[];
    reviews: Row[];
    relations: Row[];
    selectorMaps: Row[];
    media: Row[];
    folders: Row[];
};

const DAY_MS = 86_400_000;
/** Snapshots are kept 2 days, then deleted to save space (the newest one is
 *  always kept). Shorter than the 30-day bin, so every file a kept snapshot names
 *  is still in storage. */
const KEEP_DAYS = 2;
const KEEP_MIN = 1;
/** How long files removed by a rollback stay in Deleted items. */
const BIN_DAYS = 30;

/** Brotli at its strongest setting with the largest window: JSON content shrinks
 *  to a small fraction (typically 5 to 10%). Slow to write, fast to read. */
const compress = (b: Buffer) =>
    brotliCompressSync(b, { params: { [z.BROTLI_PARAM_QUALITY]: 11, [z.BROTLI_PARAM_LGWIN]: 24, [z.BROTLI_PARAM_MODE]: z.BROTLI_MODE_TEXT, [z.BROTLI_PARAM_SIZE_HINT]: b.length } });
/** A bulk delete of at least this many items takes a snapshot first. */
export const BULK_DELETE_SNAPSHOT_AT = 5;

/**
 * The safety net under everything else: whole-workspace snapshots of the content
 * and media library, and a one-step master rollback to one. Snapshots are taken
 * daily, on demand, before any bulk delete, and before every rollback (so a
 * rollback can itself be undone). Users, roles, tokens and settings are not part
 * of it: a rollback never locks anyone out.
 */
@Injectable()
export class BackupsService implements OnModuleInit, OnModuleDestroy {
    private readonly logger = new Logger(BackupsService.name);
    private timer: ReturnType<typeof setInterval> | null = null;

    constructor(
        private readonly prisma: PrismaService,
        @Optional() private readonly redis?: RedisService,
        @Optional() private readonly webhooks?: WebhooksService,
        @Optional() private readonly cache?: CacheService,
        @Optional() private readonly audit?: AuditService,
    ) {}

    onModuleInit() {
        this.timer = setInterval(() => void this.daily(), 3_600_000);
        this.timer.unref?.();
    }

    onModuleDestroy() {
        if (this.timer) clearInterval(this.timer);
    }

    /** Take a daily snapshot of every workspace that hasn't had one in 24 hours
     *  (skipped when nothing changed), and prune old ones. */
    async daily(): Promise<number> {
        try {
            if (this.redis && !(await this.redis.tryAcquire("sched:backups", 55 * 60_000))) return 0;
            const since = new Date(Date.now() - DAY_MS);
            const workspaces = await this.prisma.workspace.findMany({ where: { backups: { none: { kind: "daily", createdAt: { gte: since } } } }, select: { id: true } });
            for (const w of workspaces) await this.create(w.id, "daily");
            return workspaces.length;
        } catch (e) {
            this.logger.warn(`daily backups failed: ${e instanceof Error ? e.message : e}`);
            return 0;
        }
    }

    private async snapshot(workspaceId: string): Promise<Snapshot> {
        const ws = { workspaceId };
        const [types, entries, relations, selectorMaps, media, folders] = await Promise.all([
            this.prisma.contentType.findMany({ where: ws }),
            // The title column is generated by the database from data; never copied.
            this.prisma.contentEntry.findMany({ where: ws, omit: { title: true } }),
            this.prisma.entryRelation.findMany({ where: ws }),
            this.prisma.selectorMap.findMany({ where: ws }),
            this.prisma.media.findMany({ where: ws }),
            this.prisma.mediaFolder.findMany({ where: ws }),
        ]);
        const reviews = await this.prisma.contentReview.findMany({ where: { entry: ws } });
        return { format: 1, takenAt: new Date().toISOString(), types, entries, reviews, relations, selectorMaps, media, folders } as unknown as Snapshot;
    }

    /** Take a snapshot now. */
    async create(workspaceId: string, kind: "daily" | "manual" | "pre-bulk-delete" | "pre-rollback", note?: string) {
        const snap = await this.snapshot(workspaceId);
        const { takenAt: _at, ...content } = snap;
        void _at;
        const hash = createHash("sha256").update(JSON.stringify(content)).digest("hex");
        // Nothing changed since the last snapshot: a daily one would be a copy.
        if (kind === "daily") {
            const last = await this.prisma.workspaceBackup.findFirst({ where: { workspaceId }, orderBy: { createdAt: "desc" }, select: { id: true, kind: true, note: true, counts: true, sizeBytes: true, createdBy: true, createdAt: true, hash: true } });
            if (last?.hash === hash) {
                await this.prune(workspaceId);
                return last;
            }
        }
        const data = compress(Buffer.from(JSON.stringify(snap)));
        const who = currentActor();
        const counts = { types: snap.types.length, entries: snap.entries.length, media: snap.media.length, relations: snap.relations.length, folders: snap.folders.length };
        const row = await this.prisma.workspaceBackup.create({
            data: { workspaceId, kind, note: note ?? null, counts, sizeBytes: data.length, data, hash, createdById: who.userId, createdBy: who.name ?? (kind === "daily" ? "Daily backup" : null) },
            select: { id: true, kind: true, note: true, counts: true, sizeBytes: true, createdBy: true, createdAt: true },
        });
        await this.prune(workspaceId);
        if (kind !== "daily") await this.audit?.log({ workspaceId, action: "workspace.backup", resource: "WorkspaceBackup", resourceId: row.id, title: kind, metadata: { counts, ...(note ? { note } : {}) } });
        return row;
    }

    /** Drop snapshots past 2 days, always keeping the newest one. */
    private async prune(workspaceId: string) {
        const keep = await this.prisma.workspaceBackup.findMany({ where: { workspaceId }, orderBy: { createdAt: "desc" }, take: KEEP_MIN, select: { id: true } });
        await this.prisma.workspaceBackup.deleteMany({ where: { workspaceId, createdAt: { lt: new Date(Date.now() - KEEP_DAYS * DAY_MS) }, id: { notIn: keep.map((k) => k.id) } } });
    }

    async list(workspaceId: string) {
        return this.prisma.workspaceBackup.findMany({
            where: { workspaceId },
            orderBy: { createdAt: "desc" },
            select: { id: true, kind: true, note: true, counts: true, sizeBytes: true, createdBy: true, createdAt: true },
        });
    }

    /** The snapshot as Brotli-compressed JSON, for keeping a copy off the server. */
    async download(workspaceId: string, id: string) {
        const b = await this.prisma.workspaceBackup.findFirst({ where: { id, workspaceId }, select: { data: true, createdAt: true } });
        if (!b) throw new NotFoundException("Backup not found.");
        await this.audit?.log({ workspaceId, action: "workspace.backup_download", resource: "WorkspaceBackup", resourceId: id });
        return b;
    }

    /**
     * Master rollback: put the workspace's content and media library back exactly
     * as the snapshot has it, in one transaction. A snapshot of the current state
     * is taken first, so this can be undone the same way. Content made after the
     * snapshot is removed (it stays in that pre-rollback snapshot); files removed
     * from the library go to Deleted items, never out of storage. Fires
     * workspace.restored so the site rebuilds.
     */
    async rollback(workspaceId: string, id: string, confirm: string) {
        const ws0 = await this.prisma.workspace.findUniqueOrThrow({ where: { id: workspaceId }, select: { name: true } });
        if (confirm.trim() !== ws0.name.trim()) throw new BadRequestException("Type the workspace name exactly to confirm the rollback.");
        const b = await this.prisma.workspaceBackup.findFirst({ where: { id, workspaceId } });
        if (!b) throw new NotFoundException("Backup not found.");
        let snap: Snapshot;
        try {
            snap = JSON.parse(brotliDecompressSync(b.data).toString("utf8")) as Snapshot;
        } catch {
            throw new BadRequestException("This backup can't be read.");
        }
        if (snap.format !== 1) throw new BadRequestException("This backup was made by a newer version.");
        const undo = await this.create(workspaceId, "pre-rollback", `before rolling back to ${b.createdAt.toISOString()}`);
        const who = currentActor();
        const ids = (rows: Row[]) => rows.map((r) => r.id);
        const typeIds = ids(snap.types);
        const entryIds = ids(snap.entries);
        const mediaIds = ids(snap.media);
        const ws = { workspaceId };

        await this.prisma.$transaction(
            async (tx) => {
                // Gone from the snapshot's world: types and entries made since (their
                // versions, reviews and links go with them by cascade).
                await tx.contentType.deleteMany({ where: { ...ws, id: { notIn: typeIds } } });
                await tx.contentEntry.deleteMany({ where: { ...ws, id: { notIn: entryIds } } });
                for (const t of snap.types) {
                    const data = { ...t, workspaceId } as Prisma.ContentTypeUncheckedCreateInput;
                    await tx.contentType.upsert({ where: { id: t.id }, create: data, update: data });
                }
                for (const e of snap.entries) {
                    const data = { ...e, workspaceId, draftData: (e.draftData ?? Prisma.DbNull) as Prisma.InputJsonValue } as Prisma.ContentEntryUncheckedCreateInput;
                    await tx.contentEntry.upsert({ where: { id: e.id }, create: data, update: data });
                }
                // Entries that come back from Deleted items bring their version history.
                const binned = await tx.deletedItem.findMany({ where: { ...ws, kind: "entry", itemId: { in: entryIds } } });
                for (const d of binned) {
                    const versions = ((d.payload as { versions?: Prisma.ContentVersionCreateManyInput[] }).versions ?? []).filter((v) => !!v);
                    if (versions.length) await tx.contentVersion.createMany({ data: versions, skipDuplicates: true });
                }
                await tx.deletedItem.deleteMany({ where: { ...ws, kind: "entry", itemId: { in: entryIds } } });
                await tx.contentReview.deleteMany({ where: { entry: ws } });
                if (snap.reviews.length) await tx.contentReview.createMany({ data: snap.reviews as unknown as Prisma.ContentReviewCreateManyInput[], skipDuplicates: true });
                await tx.entryRelation.deleteMany({ where: ws });
                if (snap.relations.length) await tx.entryRelation.createMany({ data: snap.relations as unknown as Prisma.EntryRelationCreateManyInput[], skipDuplicates: true });
                await tx.selectorMap.deleteMany({ where: ws });
                if (snap.selectorMaps.length) await tx.selectorMap.createMany({ data: snap.selectorMaps as unknown as Prisma.SelectorMapCreateManyInput[], skipDuplicates: true });

                // Files uploaded since go to Deleted items (their bytes stay in storage).
                const newer = await tx.media.findMany({ where: { ...ws, id: { notIn: mediaIds } } });
                if (newer.length) {
                    await tx.deletedItem.createMany({
                        data: newer.map((m) => ({
                            workspaceId,
                            kind: "media",
                            itemId: m.id,
                            title: m.filename,
                            detail: m.mimeType,
                            payload: JSON.parse(JSON.stringify({ media: m })) as Prisma.InputJsonValue,
                            deletedById: who.userId,
                            deletedBy: `${who.name ?? "Super Admin"} (master rollback)`,
                            purgeAt: new Date(Date.now() + BIN_DAYS * DAY_MS),
                        })),
                    });
                    await tx.media.deleteMany({ where: { id: { in: newer.map((m) => m.id) } } });
                }
                for (const m of snap.media) {
                    const data = { ...m, workspaceId } as Prisma.MediaUncheckedCreateInput;
                    await tx.media.upsert({ where: { id: m.id }, create: data, update: data });
                }
                await tx.deletedItem.deleteMany({ where: { ...ws, kind: "media", itemId: { in: mediaIds } } });
                await tx.mediaFolder.deleteMany({ where: ws });
                if (snap.folders.length) await tx.mediaFolder.createMany({ data: snap.folders as unknown as Prisma.MediaFolderCreateManyInput[], skipDuplicates: true });
            },
            { timeout: 10 * 60_000, maxWait: 30_000 },
        );

        const counts = { types: snap.types.length, entries: snap.entries.length, media: snap.media.length };
        await this.audit?.log({ workspaceId, action: "workspace.restore", resource: "WorkspaceBackup", resourceId: b.id, title: `rollback to ${b.createdAt.toISOString()}`, metadata: { backupTakenAt: b.createdAt, kind: b.kind, counts, undoBackupId: undo.id } });
        void this.webhooks?.dispatch(workspaceId, "workspace.restored", { backupId: b.id, takenAt: b.createdAt, counts });
        void this.cache?.delByPrefix(`dash:${workspaceId}:`);
        return { ok: true, restoredTo: b.createdAt, counts, undoBackupId: undo.id };
    }
}
